const COMPANY = '杭州永盛海一差别化纤维织物有限公司';
const PAGE_WIDTH = 595.28;
const PAGE_HEIGHT = 841.89;
const MARGIN = 36;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;
const BOTTOM = PAGE_HEIGHT - 44;
const MAX_PHOTO_BYTES = 12 * 1024 * 1024;
const BLACK = '#111111';
const GRAY = '#f1f1f1';

function fail(message: string): never { throw new Error(`DOCUMENT_INPUT: ${message}`); }
function clean(value: string | null | undefined): string {
  if (value == null || value === '') return '-';
  if (typeof value !== 'string' || value.length > 20000) fail('文本类型或长度无效');
  return value.replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, '');
}
function numberText(value: DocumentNumber | undefined): string {
  if (value == null || value === '') return '-';
  const raw = String(value);
  if (!/^\d+(?:\.\d+)?$/.test(raw) || raw.length > 32 || !Number.isFinite(Number(raw))) fail('数量/分值必须为非负十进制数');
  return raw;
}
function measurePair(length: DocumentNumber | undefined, weight: DocumentNumber | undefined): string {
  return `${numberText(length)} m / ${numberText(weight)} kg`;
}
function beijingTime(value: string): string {
  return new Intl.DateTimeFormat('zh-CN', { timeZone: 'Asia/Shanghai', dateStyle: 'medium', timeStyle: 'short', hour12: false }).format(new Date(value));
}
function validTimestamp(value: string): boolean {
  return typeof value === 'string' && /(?:Z|[+-]\d{2}:\d{2})$/.test(value) && Number.isFinite(Date.parse(value));
}
function originalResult(roll: ReportRoll): ReportRoll['result'] {
  return roll.inspectionHistory?.find(entry => entry.kind === 'ORIGINAL')?.result ?? roll.result;
}
function assets(options: DocumentAssets): { font: string; logo: string } {
  const base = options.assetDir ?? join(__dirname, 'assets');
  const font = join(base, 'NotoSansCJKsc-Medium.otf');
  const logo = join(base, 'yongsheng-group-blue.png');
  if (!existsSync(font) || !existsSync(logo)) throw new Error('DOCUMENT_ASSETS_MISSING: 将完整 vcans-orders/assets 复制到编译目录，或提供 assetDir');
  return { font, logo };
}
function collect(doc: PDFKit.PDFDocument, draw: () => void): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('error', reject);
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    try { draw(); doc.end(); } catch (error) { doc.destroy(); reject(error); }
  });
}
function wrap(doc: PDFKit.PDFDocument, value: string, width: number, size: number): string[] {
  doc.fontSize(size);
  const output: string[] = [];
  for (const paragraph of value.split(/\r?\n/)) {
    let current = '';
    for (const character of Array.from(paragraph)) {
      if (current && doc.widthOfString(current + character) > width) {
        output.push(current); current = '';
      }
      current += character;
    }
    output.push(current);
  }
  return output;
}

/** Explicit flow control also splits a single very long table row across pages. */
class ReportFlow {
  y = 0;
  constructor(readonly doc: PDFKit.PDFDocument, private readonly input: OrderReportInput, private readonly logo: string) {}
  page(): void {
    this.doc.addPage({ size: 'A4', margins: { top: 0, right: 0, bottom: 0, left: 0 } });
    this.doc.image(this.logo, MARGIN, 25, { width: 118 });
    this.doc.fillColor(BLACK).fontSize(12).text(COMPANY, 170, 32, { lineBreak: false });
    this.doc.fontSize(13).text('整单验布报告', 170, 55, { lineBreak: false });
    this.y = 85;
    if (this.input.example) this.text('版式样稿 · 虚构示例 · 非正式检验报告', 10);
    this.doc.moveTo(MARGIN, this.y + 2).lineTo(PAGE_WIDTH - MARGIN, this.y + 2).lineWidth(0.8).strokeColor('#333333').stroke();
    this.y += 10;
    this.text(`报告号：${clean(this.input.reportNumber)}    版本：V${this.input.version}`, 9);
    this.text(`H号：${clean(this.input.hNo)}`, 9);
    this.y += 4;
  }
  ensure(height: number): void { if (this.y + height > BOTTOM) this.page(); }
  text(text: string, size = 10, gap = 4): void {
    const lines = wrap(this.doc, text, CONTENT_WIDTH - 12, size);
    for (const line of lines) {
      this.ensure(size + 5);
      this.doc.fillColor(BLACK).fontSize(size).text(line, MARGIN + 5, this.y, { lineBreak: false });
      this.y += size + 5;
    }
    this.y += gap;
  }
  section(title: string, followingHeight = 28): void {
    this.ensure(27 + followingHeight);
    this.doc.rect(MARGIN, this.y, CONTENT_WIDTH, 22).fill(GRAY);
    this.doc.fillColor(BLACK).fontSize(11).text(title, MARGIN + 7, this.y + 4, { lineBreak: false });
    this.y += 28;
  }
  table(headers: string[], widths: number[], rows: string[][], size = 9): void {
    const lineHeight = size + 5;
    const drawHeader = (): void => {
      this.doc.rect(MARGIN, this.y, CONTENT_WIDTH, 24).fill(GRAY);
      let x = MARGIN;
      headers.forEach((heading, i) => {
        this.doc.fillColor(BLACK).fontSize(size).text(heading, x + 4, this.y + 6, { lineBreak: false });
        x += widths[i];
      });
      this.y += 26;
    };
    this.ensure(60); drawHeader();
    for (const row of rows) {
      const cells = row.map((cell, i) => wrap(this.doc, cell, widths[i] - 8, size));
      const maxLines = Math.max(...cells.map(cell => cell.length));
      let offset = 0;
      while (offset < maxLines) {
        if (this.y + lineHeight + 10 > BOTTOM) { this.page(); drawHeader(); }
        const available = Math.max(1, Math.floor((BOTTOM - this.y - 10) / lineHeight));
        const count = Math.min(available, maxLines - offset);
        let x = MARGIN;
        for (let col = 0; col < cells.length; col++) {
          for (let line = 0; line < count; line++) {
            this.doc.fillColor(BLACK).fontSize(size).text(cells[col][offset + line] ?? '', x + 4, this.y + 4 + line * lineHeight, { lineBreak: false });
          }
          x += widths[col];
        }
        this.y += count * lineHeight + 9;
        this.doc.moveTo(MARGIN, this.y).lineTo(PAGE_WIDTH - MARGIN, this.y).lineWidth(0.5).strokeColor('#888888').stroke();
        this.y += 2; offset += count;
      }
    }
    this.y += 9;
  }
  photo(photo: ReportPhoto, roll: ReportRoll, inspectionLabel?: string): void {
    const defectName = photo.defectName?.trim();
    const position = photo.positionM == null ? '' : String(photo.positionM).trim();
    const title = photo.caption?.trim();
    const caption = `卷 ${clean(roll.rollNo)} / 缸 ${clean(roll.lotNo)}${inspectionLabel ? ` / ${inspectionLabel}` : ''}${defectName ? ` · ${clean(defectName)}` : ''}${position ? ` · 米位 ${numberText(photo.positionM)} m` : ''}${title ? `\n${clean(title)}` : ''}`;
    // Large captions flow normally; they are never silently clipped into the image box.
    this.ensure(220);
    this.text(caption, 9);
    this.ensure(190);
    this.doc.rect(MARGIN + 5, this.y, CONTENT_WIDTH - 10, 180).lineWidth(0.5).strokeColor('#888888').stroke();
    this.doc.image(photo.bytes, MARGIN + 11, this.y + 6, { fit: [CONTENT_WIDTH - 22, 168], align: 'center', valign: 'center' });
    this.y += 192;
  }
  finish(): void {
    const range = this.doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      this.doc.switchToPage(i);
      const footer = this.input.example ? '仅供版式讨论；所有数据均为虚构示例' : '检验结论仅针对实际受检卷；主管确认表示记录准确';
      this.doc.fillColor(BLACK).fontSize(8).text(footer, MARGIN, PAGE_HEIGHT - 27, { lineBreak: false });
      this.doc.text(`${i + 1} / ${range.count}`, PAGE_WIDTH - MARGIN - 38, PAGE_HEIGHT - 27, { lineBreak: false });
    }
  }
}

function validateReport(input: OrderReportInput): void {
  if (!input.hNo?.trim() || input.hNo.length > 128 || !input.reportNumber?.trim() || input.reportNumber.length > 128) fail('缺少有效报告编号或H号');
  if (!Number.isSafeInteger(input.version) || input.version < 1) fail('报告版本必须为正整数');
  if (!validTimestamp(input.confirmedAt)) fail('确认时间需包含时区');
  if (!input.confirmedByName?.trim() || !input.lines.length || !input.rolls.length) fail('报告缺少确认人/明细/布卷');
  if (input.rolls.length > 10000 || input.lines.length > 1000) fail('报告规模超过安全上限');
  const lineIds = new Set(input.lines.map(line => line.id));
  if (lineIds.size !== input.lines.length) fail('重复订单明细');
  if (new Set(input.rolls.map(roll => roll.id)).size !== input.rolls.length) fail('重复布卷');
  if (!Number.isSafeInteger(input.originalRequiredRolls) || input.originalRequiredRolls < 1 || input.originalRequiredRolls !== input.rolls.filter(roll => roll.originalSample).length) fail('原定应检数量与选卷不一致');
  let photoBytes = 0;
  let photoCount = 0;
  let defectCount = 0;
  const withHistory = input.rolls.some(roll => (roll.inspectionHistory?.length ?? 0) > 0);
  const historyIds = new Set<string>();
  for (const roll of input.rolls) {
    if (!lineIds.has(roll.lineId)) fail('布卷没有对应订单明细');
    if (!['PASS', 'FAIL', 'UNINSPECTED', 'INCOMPLETE'].includes(roll.result)) fail('未知布卷结论');
    if (roll.originalSample && !['PASS', 'FAIL'].includes(roll.result)) fail('原定应检布卷尚未完成');
    if (roll.pendingAdditionalInspectionCount != null && (!Number.isSafeInteger(roll.pendingAdditionalInspectionCount) || roll.pendingAdditionalInspectionCount < 0 || roll.pendingAdditionalInspectionCount > 10000)) fail('待完成追加检验次数无效');
    const history = roll.inspectionHistory ?? [];
    if (history.length > 500) fail('单卷检验历史超过安全上限');
    if (withHistory && ['PASS', 'FAIL'].includes(roll.result) && history.length === 0) fail('新历史报告的受检卷必须提供已审核历史');
    if (history.length) {
      const selected = history.find(entry => entry.id === roll.latestReviewedInspectionId);
      if (!selected || selected.result !== roll.result) fail('最新已审核记录与卷汇总结论不一致');
      if (history.filter(entry => entry.kind === 'ORIGINAL').length !== (roll.originalSample ? 1 : 0)) fail('原定检验依据与选卷不一致');
      for (const entry of history) {
        if (!entry.id?.trim() || historyIds.has(entry.id)) fail('检验历史标识为空或重复');
        historyIds.add(entry.id);
        if (!['ORIGINAL', 'ADDITIONAL'].includes(entry.kind) || !['PASS', 'FAIL'].includes(entry.result)) fail('检验历史只能包含已审核的原定或追加结果');
        if (entry.kind === 'ADDITIONAL' && !roll.additionalSample) fail('追加检验历史缺少追加选卷标识');
        if (!validTimestamp(entry.inspectedAt) || !validTimestamp(entry.reviewedAt)) fail('检验历史时间需包含时区');
      }
    }
    // History entries are authoritative. Legacy aggregate defects/photos are not mixed
    // into an attempt, which would make an original failure look like a later retest.
    const records = history.length ? history : [roll];
    for (const record of records) {
      if ((record.defects?.length ?? 0) > 5000 || (record.photos?.length ?? 0) > 100) fail('单次检验疵点/照片超过安全上限');
      defectCount += record.defects?.length ?? 0;
      for (const photo of record.photos ?? []) {
        if (!Buffer.isBuffer(photo.bytes) || photo.bytes.length === 0 || photo.bytes.length > MAX_PHOTO_BYTES) fail('照片必须为有效预载图片');
        const png = photo.bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
        const jpeg = photo.bytes[0] === 0xff && photo.bytes[1] === 0xd8;
        if (!png && !jpeg) fail('照片仅支持PNG/JPEG');
        if (png) {
          if (photo.bytes.length < 24) fail('PNG头部不完整');
          const width = photo.bytes.readUInt32BE(16); const height = photo.bytes.readUInt32BE(20);
          if (width === 0 || height === 0 || width > 12000 || height > 12000 || width * height > 30000000) fail('照片像素尺寸超过安全上限');
        }
        photoCount++;
        photoBytes += photo.bytes.length;
      }
    }
  }
  if (photoBytes > 100 * 1024 * 1024 || photoCount > 500 || defectCount > 20000) fail('报告疵点/照片总量超过安全上限');
}

async function renderReport(input: OrderReportInput, options: DocumentAssets): Promise<Buffer> {
  validateReport(input);
  const resource = assets(options);
  const doc = new PDFDocument({ autoFirstPage: false, bufferPages: true, compress: true, info: {
    Title: `${input.hNo} 整单验布报告 V${input.version}`, Author: COMPANY,
    CreationDate: new Date(input.confirmedAt), ModDate: new Date(input.confirmedAt),
  } });
  doc.registerFont('Chinese', resource.font).font('Chinese');
  return collect(doc, () => {
    const flow = new ReportFlow(doc, input, resource.logo);
    flow.page();
    // Keep the compact outcome on page one; full sales details may span many pages.
    flow.section('检验覆盖与结论');
    const inspected = input.rolls.filter(roll => roll.result === 'PASS' || roll.result === 'FAIL');
    const originalInspected = inspected.filter(roll => roll.originalSample).length;
    const failCount = inspected.filter(roll => roll.result === 'FAIL').length;
    const uninspected = input.rolls.filter(roll => roll.result === 'UNINSPECTED').length;
    const incomplete = input.rolls.filter(roll => roll.result === 'INCOMPLETE').length;
    const withHistory = input.rolls.some(roll => (roll.inspectionHistory?.length ?? 0) > 0);
    const pendingAdditional = input.rolls.reduce((total, roll) => total + (roll.pendingAdditionalInspectionCount ?? 0), 0);
    flow.text(`整单 ${input.rolls.length} 卷；原定应检 ${input.originalRequiredRolls} 卷，原定已检 ${originalInspected} 卷。`, 9.5);
    flow.text(`${withHistory ? '最新已审核结果：' : ''}已检合格 ${inspected.length - failCount} 卷 / 不合格 ${failCount} 卷；未检 ${uninspected} 卷${incomplete ? `；其他检验未完成 ${incomplete} 卷` : ''}。未检卷不作质量判定。`, 9.5);
    if (withHistory) {
      const originalFail = input.rolls.filter(roll => roll.originalSample && originalResult(roll) === 'FAIL').length;
      flow.text(`原定受检结果：合格 ${originalInspected - originalFail} 卷 / 不合格 ${originalFail} 卷；复验不增加实物卷数，原定记录保留。`, 9.5);
    }
    if (pendingAdditional > 0) flow.text(`追加检验待完成或审核：${pendingAdditional} 次。`, 9.5);
    flow.text(`检验要求：${clean(input.inspectionPlanDescription)}`, 9.5);
    if (input.pendingActions?.length) for (const action of input.pendingActions) flow.text(`待处理：${clean(action)}`, 9.5);
    flow.section('订单与面料');
    input.lines.forEach((line, i) => {
      flow.text(`明细 ${i + 1}  客户单号：${clean(line.customerOrderNo)}  品名：${clean(line.productName)}`, 9.5);
      flow.text(`规格：${clean(line.specification)}  颜色：${clean(line.color)}  订单量：${numberText(line.quantity)} ${clean(line.quantityUnit)}`, 9.5);
    });
    flow.section(withHistory ? '逐卷结果（最新已审核）' : '逐卷结果');
    const resultNames = { PASS: '合格', FAIL: '不合格', UNINSPECTED: '未判定', INCOMPLETE: '未完成' };
    flow.table(['明细/卷号', '缸号', '厂家标称 米/kg', '实测 米/kg', '检验范围', withHistory ? '最新结果' : '结果'], [100, 66, 116, 116, 70, CONTENT_WIDTH - 468], input.rolls.map(roll => [
      `${input.lines.findIndex(line => line.id === roll.lineId) + 1} / ${clean(roll.rollNo)}`, clean(roll.lotNo),
      measurePair(roll.nominalLengthM, roll.nominalWeightKg), measurePair(roll.measuredLengthM, roll.measuredWeightKg),
      roll.originalSample ? (roll.additionalSample ? '原定+加抽' : '原定受检') : roll.additionalSample ? '后续加抽' : ['PASS', 'FAIL'].includes(roll.result) ? '其他受检' : '未抽检', resultNames[roll.result],
    ]));
    const detailRolls = input.rolls.filter(roll => roll.inspectionHistory?.length || roll.pendingAdditionalInspectionCount || roll.defects?.length || roll.photos?.length || roll.conclusionNote || roll.totalPoints != null || roll.normalizedScore != null);
    if (detailRolls.length) {
      flow.section(withHistory ? '检验历史、疵点与检查说明' : '疵点、计分与检查说明');
      for (const roll of detailRolls) {
        flow.text(`卷 ${clean(roll.rollNo)} / 缸 ${clean(roll.lotNo)}`, 10);
        if (roll.pendingAdditionalInspectionCount) flow.text(`另有 ${roll.pendingAdditionalInspectionCount} 次追加检验待完成或审核。`, 9.5);
        const renderDetails = (record: ReportRoll | ReportInspectionHistoryEntry, inspectionLabel?: string): void => {
          if (record.conclusionNote) flow.text(clean(record.conclusionNote), 9.5);
          if (record.totalPoints != null || record.normalizedScore != null) flow.text(`总扣分：${numberText(record.totalPoints)}；折算分：${numberText(record.normalizedScore)} ${clean(record.scoreUnit)}`, 9.5);
          if (record.defects?.length) flow.table(['疵点名称', '米位(m)', '长度×宽度(cm)', '扣分', '备注'], [120, 70, 112, 50, CONTENT_WIDTH - 352], record.defects.map(defect => [
            clean(defect.name), numberText(defect.positionM), `${numberText(defect.lengthCm)} × ${numberText(defect.widthCm)}`, numberText(defect.points), clean(defect.note),
          ]));
          for (const photo of record.photos ?? []) flow.photo(photo, roll, inspectionLabel);
        };
        if (roll.inspectionHistory?.length) {
          for (const entry of roll.inspectionHistory) {
            const label = `${entry.kind === 'ORIGINAL' ? '原定检验' : '追加复验'} ${clean(entry.inspectionNumber ?? entry.id)}`;
            flow.ensure(95);
            flow.text(`${label}（已审核）${entry.id === roll.latestReviewedInspectionId ? ' · 最新已审核' : ''}`, 10);
            flow.text(`本次结果：${resultNames[entry.result]}；提交时间：${beijingTime(entry.inspectedAt)}；审核时间：${beijingTime(entry.reviewedAt)}（北京时间）`, 9.5);
            flow.text(`检验员：${clean(entry.inspectorName)}；审核人：${clean(entry.reviewerName)}`, 9.5);
            flow.text(`本次标准：${clean(entry.standardName)}`, 9.5);
            if (entry.standardDescription) flow.text(clean(entry.standardDescription), 9.5);
            if (entry.measuredLengthM != null || entry.measuredWeightKg != null) flow.text(`本次实测：${measurePair(entry.measuredLengthM, entry.measuredWeightKg)}`, 9.5);
            renderDetails(entry, label);
          }
        } else renderDetails(roll);
      }
    }
    flow.section('检验依据与确认', 130);
    flow.text(`标准：${clean(input.standardName)}`, 9.5);
    if (input.standardDescription) flow.text(clean(input.standardDescription), 9.5);
    flow.text(`检验员：${input.inspectorNames.map(clean).join('、') || '-'}`, 9.5);
    const time = beijingTime(input.confirmedAt);
    flow.text(`整单确认：${clean(input.confirmedByName)}  ${time}（北京时间）`, 9.5);
    flow.text('审核状态：主管已确认记录准确；不等同所有布卷合格。', 9.5);
    if (input.notes) flow.text(`备注：${clean(input.notes)}`, 9.5);
    flow.finish();
  });
}

export function labelMeasurement(label: RollLabelInput, field: 'length' | 'weight'): { value: string; source: '实测' | '标称' | '未填写' } {
  const measured = field === 'length' ? label.measuredLengthM : label.measuredWeightKg;
  const nominal = field === 'length' ? label.nominalLengthM : label.nominalWeightKg;
  const value = label.purpose === 'REPRINT' && measured != null ? measured : nominal;
  return { value: numberText(value), source: value == null ? '未填写' : label.purpose === 'REPRINT' && measured != null ? '实测' : '标称' };
}

async function renderLabels(labels: RollLabelInput[], options: LabelOptions): Promise<Buffer> {
  if (!Array.isArray(labels) || labels.length === 0 || labels.length > 500) fail('标签数量须为1至500');
  const widthMm = options.widthMm ?? 100;
  const heightMm = options.heightMm ?? 70;
  if (!Number.isFinite(widthMm) || widthMm < 70 || widthMm > 150 || !Number.isFinite(heightMm) || heightMm < 50 || heightMm > 150) fail('标签纸宽需70至150mm，高需50至150mm');
  const { font } = assets(options);
  const mm = 72 / 25.4;
  const w = widthMm * mm; const h = heightMm * mm; const margin = 8;
  const doc = new PDFDocument({ autoFirstPage: false, compress: true, info: { Title: '永盛布卷标签', Author: COMPANY } });
  doc.registerFont('Chinese', font).font('Chinese');
  return collect(doc, () => {
    for (const label of labels) {
      if (!label.hNo?.trim() || !label.lotNo?.trim() || !label.rollNo?.trim() || !label.qrCode?.trim() || Buffer.byteLength(label.qrCode) > 256) fail('标签缺少H号/缸号/卷号/有效原二维码');
      if (!['INITIAL', 'REPRINT'].includes(label.purpose)) fail('打印用途无效');
      doc.addPage({ size: [w, h], margin: 0 });
      let y = margin;
      const text = (value: string, x: number, maxWidth: number, size: number): number => {
        const lines = wrap(doc, value, maxWidth, size);
        if (y + lines.length * (size + 3) > h - margin) fail('标签文字过长，请使用更大纸张');
        for (const line of lines) { doc.fillColor('#000000').fontSize(size).text(line, x, y, { lineBreak: false }); y += size + 3; }
        return lines.length * (size + 3);
      };
      text(COMPANY, margin, w - margin * 2, 8);
      text(`H号：${clean(label.hNo)}`, margin, w - margin * 2, 8.5);
      text(`缸号：${clean(label.lotNo)}  卷号：${clean(label.rollNo)}`, margin, w - margin * 2, 8.5);
      y += 3;
      const bodyTop = y;
      const qrSize = Math.min(34 * mm, (w - 2 * margin) * 0.38);
      const qrX = w - margin - qrSize;
      const leftWidth = qrX - margin - 8;
      text(`品名：${clean(label.productName)}`, margin, leftWidth, 8);
      text(`规格：${clean(label.specification)}`, margin, leftWidth, 8);
      text(`颜色：${clean(label.color)}`, margin, leftWidth, 8);
      text(`客户单号：${clean(label.customerOrderNo)}`, margin, leftWidth, 8);
      const length = labelMeasurement(label, 'length'); const weight = labelMeasurement(label, 'weight');
      text(`米数：${length.value} m（${length.source}）`, margin, leftWidth, 8);
      text(`重量：${weight.value} kg（${weight.source}）`, margin, leftWidth, 8);
      const qr = QRCode.create(label.qrCode, { errorCorrectionLevel: 'M' });
      const quiet = 4; const count = qr.modules.size; const module = qrSize / (count + quiet * 2);
      if (module / mm < 0.35) fail('二维码过密，请使用更大标签或较短原卷标识');
      const payloadLines = wrap(doc, label.qrCode, qrSize, 7);
      if (bodyTop + qrSize + 4 + payloadLines.length * 10 > h - margin) fail('二维码及编号超出纸张，请使用更大标签');
      doc.rect(qrX, bodyTop, qrSize, qrSize).fill('#ffffff');
      doc.fillColor('#000000');
      for (let row = 0; row < count; row++) for (let col = 0; col < count; col++) {
        if (qr.modules.get(row, col)) doc.rect(qrX + (col + quiet) * module, bodyTop + (row + quiet) * module, module, module).fill();
      }
      payloadLines.forEach((line, i) => doc.fontSize(7).text(line, qrX, bodyTop + qrSize + 4 + i * 10, { lineBreak: false }));
    }
  });
}
