import { randomUUID } from 'node:crypto';
import { adminLogin, api, bindWechat, createTestApp, type TestContext } from './helpers';

const enabled = process.env.VCANS_CODE_TEST_DATABASE_URL;
const run = enabled ? describe : describe.skip;
run('H订单隔离HTTP烟测', () => {
  let ctx: TestContext;
  const suffix = randomUUID().slice(0, 8);
  beforeAll(async () => {
    const u = new URL(enabled!);
    if (!['localhost', '127.0.0.1'].includes(u.hostname) || u.port === '5432' || !u.pathname.startsWith('/fqc_vcans_code_') || process.env.DATABASE_URL !== enabled) throw new Error('拒绝非代码岗隔离库');
    ctx = await createTestApp();
  });
  afterAll(async () => { if (ctx) await ctx.app.close(); });
  it('业务经理能按本部门选主管、建H单并查询；未确认报告不可读取', async () => {
    const admin = await adminLogin(ctx.app);
    const department = await api(ctx.app, admin).post('/departments', { code: `HTTP-${suffix}`, name: 'TEST业务部' });
    expect(department.status).toBe(201);
    const qc = await api(ctx.app, admin).post('/departments', { code: `HTTP-Q-${suffix}`, name: 'TEST质检部' });
    expect(qc.status).toBe(201);
    const sup = await api(ctx.app, admin).post('/users', { employeeNo: `HTTP-SUP-${suffix}`, name: 'TEST主管', departmentId: qc.body.id, roles: [{ role: 'QC_SUPERVISOR', departmentId: qc.body.id }] });
    expect(sup.status).toBe(201);
    const number = `HTTP-M-${suffix}`;
    const manager = await api(ctx.app, admin).post('/users', { employeeNo: number, name: 'TEST经理', departmentId: department.body.id, roles: [{ role: 'BUSINESS_MANAGER', departmentId: department.body.id }] });
    expect(manager.status).toBe(201);
    const token = (await bindWechat(ctx.app, admin, manager.body.id, number, `http-${suffix}`)).accessToken;
    expect((await api(ctx.app, token).get('/orders/options')).status).toBe(200);
    const missingMode = { hNo: `TEST-HTTP-${suffix}`, businessDepartmentId: department.body.id, supervisorId: sup.body.id, plan: { mode: 'FULL' }, lines: [{ customerOrderNo: 'TEST-PO' }] };
    expect((await api(ctx.app, token).post('/orders', missingMode)).status).toBe(400);
    const created = await api(ctx.app, token).post('/orders', { ...missingMode, requiredStandardMode: 'FACTORY' });
    expect(created.status).toBe(201);
    const list = await api(ctx.app, token).get('/orders?q=test-po');
    expect(list.status).toBe(200);
    expect(list.body.items.some((item: { id: string }) => item.id === created.body.id)).toBe(true);
    const detail = await api(ctx.app, token).get(`/orders/${created.body.id}`);
    expect(detail.status).toBe(200);
    expect(detail.body.rolls).toEqual([]);
    expect((await api(ctx.app, token).get(`/orders/${created.body.id}/reports/1/pdf`)).status).toBe(404);
    await ctx.prisma.notification.create({ data: { userId: manager.body.id, type: 'TEST', title: 'TEST归档通知', body: 'TEST归档', entityType: 'VcansOrder', entityId: created.body.id } });
    await ctx.prisma.vcansOrder.update({ where: { id: created.body.id }, data: { purpose: 'TEST' } });
    const hidden = await api(ctx.app, token).get('/orders?q=test-po');
    expect(hidden.body.items.some((item: { id: string }) => item.id === created.body.id)).toBe(false);
    expect((await api(ctx.app, token).get(`/orders/${created.body.id}`)).status).toBe(404);
    const notices = await api(ctx.app, token).get('/notifications');
    expect(notices.status).toBe(200);
    expect(notices.body.items.some((item: { title: string }) => item.title === 'TEST归档通知')).toBe(false);
    await ctx.prisma.vcansOrder.update({ where: { id: created.body.id }, data: { purpose: 'UNKNOWN' } });
    expect((await api(ctx.app, token).get(`/orders/${created.body.id}`)).status).toBe(200);
    const inspectorNo = `HTTP-INS-${suffix}`;
    const inspector = await api(ctx.app, admin).post('/users', { employeeNo: inspectorNo, name: 'TEST验布员', departmentId: qc.body.id, roles: [{ role: 'INSPECTOR', departmentId: qc.body.id }] });
    expect(inspector.status).toBe(201);
    const inspectorToken = (await bindWechat(ctx.app, admin, inspector.body.id, inspectorNo, `ins-${suffix}`)).accessToken;
    const standard = await ctx.prisma.qualityStandard.findFirstOrThrow({ where: { kind: 'FOUR_POINT' } });
    const template = await ctx.prisma.inspectionTemplate.findFirstOrThrow();
    const task = await ctx.prisma.qcTask.create({ data: { taskNo: `HTTP-TASK-${suffix}`, title: 'TEST旧任务', purpose: 'TEST', assigneeId: inspector.body.id, createdById: sup.body.id, fourPointStandardId: standard.id, templateId: template.id } });
    expect((await api(ctx.app, inspectorToken).get(`/tasks/${task.id}`)).status).toBe(404);
    const mine = await api(ctx.app, inspectorToken).get('/tasks/mine');
    expect(mine.body.some((item: { id: string }) => item.id === task.id)).toBe(false);
    await ctx.prisma.qcTask.update({ where: { id: task.id }, data: { purpose: 'UNKNOWN' } });
    expect((await api(ctx.app, inspectorToken).get(`/tasks/${task.id}`)).status).toBe(200);
    const fabric = await ctx.prisma.fabric.create({ data: { code: `HTTP-FAB-${suffix}`, nameZh: 'TEST面料', purpose: 'TEST' } });
    const lot = await ctx.prisma.productionLot.create({ data: { fabricId: fabric.id, lotNo: `HTTP-LOT-${suffix}` } });
    expect((await api(ctx.app, admin).get('/lots')).body.items.some((item: { id: string }) => item.id === lot.id)).toBe(false);
    expect((await api(ctx.app, admin).post('/lots', { fabricId: fabric.id, lotNo: `HTTP-NEW-${suffix}` })).status).toBe(400);
    expect((await api(ctx.app, admin).put(`/lots/${lot.id}`, { fabricId: fabric.id, lotNo: lot.lotNo })).status).toBe(404);
    const roll = await ctx.prisma.fabricRoll.create({ data: { rollNo: `HTTP-ROLL-${suffix}`, qrCode: `HT${suffix.toUpperCase()}`, fabricId: fabric.id, lotId: lot.id, createdById: sup.body.id } });
    const testTask = await ctx.prisma.qcTask.create({ data: { taskNo: `HTTP-TEST-${suffix}`, title: 'TEST混用任务', purpose: 'TEST', assigneeId: inspector.body.id, createdById: sup.body.id, fourPointStandardId: standard.id, templateId: template.id } });
    await ctx.prisma.qcTaskRoll.createMany({ data: [{ taskId: task.id, rollId: roll.id }, { taskId: testTask.id, rollId: roll.id }] });
    const parent = await api(ctx.app, inspectorToken).get(`/tasks/${task.id}`);
    expect(parent.status).toBe(200); expect(parent.body.rolls[0].roll.fabric).toBeNull();
    expect((await api(ctx.app, inspectorToken).get(`/rolls/by-qr/${roll.qrCode}`)).status).toBe(403);
    expect((await api(ctx.app, inspectorToken).get(`/tasks/${testTask.id}`)).status).toBe(404);
    const taskRolls = await ctx.prisma.qcTaskRoll.findMany({ where: { rollId: roll.id } });
    const standardVersion = await ctx.prisma.standardVersion.findFirstOrThrow({ where: { standardId: standard.id, status: 'PUBLISHED' } });
    const inspectionData = { rollId: roll.id, inspectorId: inspector.body.id, mode: 'MANUAL' as const, scope: 'FULL' as const, fourPointVersionId: standardVersion.id, standardSnapshot: { fourPoint: { isDevDefault: true }, customer: null }, templateSnapshot: { measurements: [] }, specSnapshot: { fabricName: '历史冻结资料' } };
    const historical = await ctx.prisma.rollInspection.create({ data: { ...inspectionData, inspectionNo: `HTTP-HIST-${suffix}`, taskId: task.id, taskRollId: taskRolls.find(x => x.taskId === task.id)!.id } });
    const archived = await ctx.prisma.rollInspection.create({ data: { ...inspectionData, inspectionNo: `HTTP-ARCH-${suffix}`, taskId: testTask.id, taskRollId: taskRolls.find(x => x.taskId === testTask.id)!.id } });
    const historicalDetail = await api(ctx.app, inspectorToken).get(`/inspections/${historical.id}`);
    expect(historicalDetail.status).toBe(200); expect(historicalDetail.body.historicalTestStandard).toBe(true); expect(historicalDetail.body.roll.fabric).toBeNull();
    expect((await api(ctx.app, inspectorToken).get(`/inspections/${archived.id}`)).status).toBe(404);
  });
});
